
CREATE TABLE FACULTY1 (
    FID NUMBER PRIMARY KEY,
    NAME VARCHAR2(20),
    SALARY NUMBER,
    DEPT VARCHAR2(10),
    DEPENDENTS VARCHAR2(20)
);

CREATE TABLE COURSES (
    CID NUMBER PRIMARY KEY,
    NAME VARCHAR2(20),
    SEM NUMBER,
    YEAR NUMBER,
    FACULTYID NUMBER,
    FOREIGN KEY (FACULTYID) REFERENCES FACULTY1(FID)
);

CREATE TABLE STUDENTS (
    SID NUMBER PRIMARY KEY,
    NAME VARCHAR2(20),
    DEPT VARCHAR2(10),
    YEAR NUMBER,
    SEM NUMBER,
    GRADEPOINT NUMBER,
    GRADE VARCHAR2(2),
    CID NUMBER,
    FOREIGN KEY (CID) REFERENCES COURSES(CID)
);


