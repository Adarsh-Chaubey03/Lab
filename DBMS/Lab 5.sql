
CREATE TABLE FACULTY1 (
 FId NUMBER PRIMARY KEY,
 Name VARCHAR2(20),
 Salary NUMBER,
 Dept VARCHAR2(10),
 Dependents VARCHAR2(20)
);

CREATE TABLE STUDENTS (
 SId NUMBER PRIMARY KEY,
 Name VARCHAR2(20),
 Dept VARCHAR2(10),
 Year NUMBER,
 Sem NUMBER,
 GradePoint NUMBER,
 Grade VARCHAR2(2),
 CId NUMBER
);

CREATE TABLE COURSES (
 CId NUMBER PRIMARY KEY,
 Name VARCHAR2(20),
 Sem NUMBER,
 Year NUMBER,
 FacultyId NUMBER
);


