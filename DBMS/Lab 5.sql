CREATE TABLE FACULTY1 (
 FID NUMBER PRIMARY KEY,
 NAME VARCHAR2(20),
 SALARY NUMBER,
 DEPT VARCHAR2(10),
 DEPENDENTS VARCHAR2(20)
);

CREATE TABLE STUDENTS (
 SID NUMBER PRIMARY KEY,
 NAME VARCHAR2(20),
 DEPT VARCHAR2(10),
 YEAR NUMBER,
 SEM NUMBER,
 GRADEPOINT NUMBER,
 GRADE VARCHAR2(2),
 CID NUMBER
);

CREATE TABLE COURSES (
 CID NUMBER PRIMARY KEY,
 NAME VARCHAR2(20),
 SEM NUMBER,
 YEAR NUMBER,
 FACULTYID NUMBER
);

