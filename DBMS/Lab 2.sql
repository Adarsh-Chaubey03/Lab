
CREATE TABLE FACULTY(
    F_ID NUMBER(5) NOT NULL PRIMARY KEY,
    F_NAME VARCHAR(10),
    RESEARCH VARCHAR(15)
);

CREATE TABLE DEPARTMENT(
    D_NO NUMBER(5) NOT NULL PRIMARY KEY,
    D_NAME VARCHAR(10),
    NO_OF_STUDENT NUMBER(5)
);

CREATE TABLE STUDENT(
     ID NUMBER(5) NOT NULL PRIMARY KEY,
     NAME VARCHAR(10),
     SEM NUMBER(5),
     ENROLLED_YEAR NUMBER(5),
     CREDIT NUMBER(5),
     DEPT_NO NUMBER(5),
     FACUL_ID NUMBER(5),
     FOREIGN KEY(DEPT_NO) REFERENCES DEPARTMENT(D_NO),
     FOREIGN KEY(FACUL_ID) REFERENCES FACULTY(F_ID)
);

