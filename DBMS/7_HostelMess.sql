

CREATE TABLE HOSTEL(
HNO INT PRIMARY KEY,
HNAME VARCHAR(10),
TYPE VARCHAR(1)
);

CREATE TABLE MENU(
HNO INT,
DAY VARCHAR(10),
BREAKFAST VARCHAR(10),
LUNCH VARCHAR(10),
DINNER VARCHAR(10),
FOREIGN KEY (HNO) REFERENCES HOSTEL(HNO)
);

CREATE TABLE WARDEN(
WNAME VARCHAR(10),
QUAL VARCHAR(10),
HNO INT,
FOREIGN KEY (HNO) REFERENCES HOSTEL(HNO)
);

CREATE TABLE STUD(
SID INT PRIMARY KEY,
SNAME VARCHAR(10),
GEN VARCHAR(1),
YEAR DATE,
HNO INT,
FOREIGN KEY (HNO) REFERENCES HOSTEL(HNO)
);



