
CREATE TABLE COMP
(
 C_ID NUMBER PRIMARY KEY,
 C_NAME VARCHAR(10),
 C_CITY VARCHAR(10)
);

CREATE TABLE EMP
(
 E_ID NUMBER PRIMARY KEY,
 E_NAME VARCHAR(10),
 SALARY DECIMAL,
 E_CITY VARCHAR(10),
 CC_ID NUMBER,
 FOREIGN KEY (CC_ID) REFERENCES COMP(C_ID)
);



