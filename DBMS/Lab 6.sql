CREATE TABLE BRANCH1 (
BID NUMBER PRIMARY KEY,
FNAME VARCHAR2(20),
FCITY VARCHAR2(20)
);

CREATE TABLE CUSTOMER1 (
CUSID NUMBER PRIMARY KEY,
CNAME VARCHAR2(20),
LOC VARCHAR2(20)
);

CREATE TABLE ACCOUNT1 (
ANO NUMBER PRIMARY KEY,
SDATE DATE,
BAL NUMBER,
CUSID NUMBER,
BID NUMBER,
FOREIGN KEY (CUSID) REFERENCES CUSTOMER1(CUSID),
FOREIGN KEY (BID) REFERENCES BRANCH1(BID)
);

CREATE TABLE TRANSACTION1 (
ANO NUMBER,
AMOUNT NUMBER,
BID NUMBER,
T_DATE DATE,
FOREIGN KEY (ANO) REFERENCES ACCOUNT1(ANO),
FOREIGN KEY (BID) REFERENCES BRANCH1(BID)
);

