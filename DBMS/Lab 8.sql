CREATE TABLE PATIENT (
PID INT PRIMARY KEY,
PNAME VARCHAR(50),
AGE INT,
GENDER VARCHAR(10),
DISEASE VARCHAR(50)
);

CREATE TABLE DOCTOR (
DID INT PRIMARY KEY,
DNAME VARCHAR(50),
SPECIALIZATION VARCHAR(50),
SALARY INT
);

CREATE TABLE APPOINTMENT (
AID INT PRIMARY KEY,
PID INT,
DID INT,
ADATE DATE,
FEES INT,
FOREIGN KEY (PID) REFERENCES PATIENT(PID),
FOREIGN KEY (DID) REFERENCES DOCTOR(DID)
);

