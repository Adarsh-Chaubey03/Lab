

CREATE TABLE PATIENT (
PId INT PRIMARY KEY,
PName VARCHAR(50),
Age INT,
Gender VARCHAR(10),
Disease VARCHAR(50)
);

CREATE TABLE DOCTOR (
DId INT PRIMARY KEY,
DName VARCHAR(50),
Specialization VARCHAR(50),
Salary INT
);

CREATE TABLE APPOINTMENT (
AId INT PRIMARY KEY,
PId INT,
DId INT,
ADate DATE,
Fees INT,
FOREIGN KEY (PId) REFERENCES PATIENT(PId),
FOREIGN KEY (DId) REFERENCES DOCTOR(DId)
);


