CREATE TABLE CUSTOMER(
    ID NUMBER(5) NOT NULL PRIMARY KEY,
    NAME VARCHAR(10)
);

CREATE TABLE CAR(
    CID NUMBER(5) NOT NULL PRIMARY KEY,
    BRAND VARCHAR(10),
    COST NUMBER(10),
    INS_AMT NUMBER(10),
    CUST_ID NUMBER(5),
    FOREIGN KEY(CUST_ID) REFERENCES CUSTOMER(ID)
);

