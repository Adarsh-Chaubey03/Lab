CREATE TRIGGER prevent_duplicate
BEFORE INSERT ON RESERVATION
FOR EACH ROW
BEGIN
    IF EXIST(
        SELECT * FROM RESERVATION WHERE TICKET_ID = NEW.TICKET_ID AND SEAT_NO = NEW .SEAT_NO
    ) THEN
    SIGNAL SQL STATE '45000'
    SET MESSAGE_TEXT = 'Seat Already booked';
    END IF;
END;